#!/usr/bin/env python3
"""Rewrites docs/MUTATION.md from docs/mutation.json, separating
  * safety theorems (headline theorems of scripts/headline.txt and the general
    theorems of LeanAID/Proofs/Lifted.lean) whose proof failed,
  * lemmas whose proof failed,
  * concrete checks (kernel-evaluated tests and counterexamples) that failed,
  * conformance (native_decide) failures.
A failing lemma stops every module that imports it from being built, so the
statements downstream are then neither confirmed nor refuted."""
import json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
res = json.load(open(os.path.join(ROOT, "docs/mutation.json")))
headline = {l.strip().split(".")[-1] for l in open(os.path.join(ROOT, "scripts/headline.txt"))
            if l.strip() and not l.strip().startswith("#")}
lifted = set(re.findall(r"^theorem (\w+)", open(os.path.join(ROOT, "LeanAID/Proofs/Lifted.lean")).read(), re.M))
concrete = {"undated_glucose_max_rate", "rate_can_exceed_maxSafeBasal", "missing_max_basal_no_clamp", "bilinear_negative"}
def kind(t):
    if t.endswith("_test") or t in concrete or re.match(r"DB_\d+_general", t): return "concrete"
    if t in headline or t in lifted: return "safety"
    return "lemma"
rows = ["| id | mutation | safety theorem broke | only lemmas broke | concrete checks broke | conformance fails |",
        "|---|---|---|---|---|---|"]
summary = {"safety": 0, "lemmaOnly": 0, "concreteOnly": 0, "conformanceOnly": 0, "nothing": 0}
for r in res:
    ts = r.get("brokenTheorems", [])
    s = [t for t in ts if kind(t) == "safety"]; l = [t for t in ts if kind(t) == "lemma"]; c = [t for t in ts if kind(t) == "concrete"]
    if s: summary["safety"] += 1
    elif l: summary["lemmaOnly"] += 1
    elif c: summary["concreteOnly"] += 1
    elif r.get("conformanceFails"): summary["conformanceOnly"] += 1
    else: summary["nothing"] += 1
    f = lambda xs: ", ".join("`%s`" % x for x in xs) or "–"
    rows.append("| %s | %s | %s | %s | %s | %s |" % (r["id"], r["description"], f(s), f(l), f(c),
                "yes" if r.get("conformanceFails") else "no"))
text = """# Mutation testing

Generated by `scripts/mutate.py` (runs the mutations) and `scripts/mutation_report.py`
(this table). Each row is one mutation of `LeanAID/Core`, built with `lake build LeanAID`.

Columns: **safety theorem broke**: the proof of a headline theorem (`scripts/headline.txt`)
or of a general theorem lifted from oref0's tests (`Proofs/Lifted.lean`) failed.
**Only lemmas broke**: proofs of supporting lemmas failed. Lean then does not build the
modules that import them, so the safety statements downstream are neither confirmed nor
refuted: the mutation is caught, but this does not show that a safety property is
violated. **Concrete checks**: kernel-evaluated tests (`*_test`, `DB_*_general` instances)
and concrete counterexamples. **Conformance**: `LeanAID/Conformance/Checks.lean`
(`native_decide`).

Summary of the strongest catch per mutation: safety theorem %(safety)d, lemma only
%(lemmaOnly)d, concrete check only %(concreteOnly)d, conformance only %(conformanceOnly)d,
not caught %(nothing)d (of %(n)d).

""" % dict(summary, n=len(res))
text += "\n".join(rows) + "\n"
old = open(os.path.join(ROOT, "docs/MUTATION.md")).read()
analysis = old[old.index("## Analysis"):] if "## Analysis" in old else ""
open(os.path.join(ROOT, "docs/MUTATION.md"), "w").write(text + "\n" + analysis)
print(summary)
