// Combine the two istanbul runs of scripts/coverage/run.sh into
// docs/coverage.json and docs/COVERAGE.md.
//   node scripts/coverage/report.js [N] [S]
// A branch is one outcome of an `if`, `?:`, `switch` case or one operand of
// `&&` / `||`, as istanbul 0.4.5 counts them.
var fs = require('fs');
var path = require('path');
var ROOT = path.resolve(__dirname, '../..');
var OUT = path.join(ROOT, 'scripts/coverage/out');
var N = process.argv[2] || '100000';
var S = process.argv[3] || '1';

function load(name) {
  var raw = JSON.parse(fs.readFileSync(path.join(OUT, name, 'coverage.json'), 'utf8'));
  var m = {};
  Object.keys(raw).forEach(function (f) {
    var i = f.indexOf('/vendor/oref0/lib/');
    if (i >= 0) m[f.slice(i + '/vendor/oref0/lib/'.length)] = raw[f];
  });
  return m;
}
var tests = load('oref0-tests');
var diff = load('difftest');

// files modelled in Lean (docs/DESIGN.md); the others are listed for reference
var MODELLED = ['determine-basal/determine-basal.js', 'basal-set-temp.js', 'round-basal.js',
  'glucose-get-last.js', 'iob/index.js', 'iob/history.js', 'iob/calculate.js', 'iob/total.js',
  'meal/history.js', 'profile/basal.js'];

function hits(v, k, i) { return v && v.b[k] ? v.b[k][i] > 0 : false; }

var files = Object.keys(tests).concat(Object.keys(diff)).filter(function (f, i, a) {
  return a.indexOf(f) === i;
}).sort();

var result = { generated: new Date().toISOString(), oref0: 'vendor/oref0 (0.7.1)',
  difftest: { cases: Number(N), seed: Number(S) }, files: {} };

files.forEach(function (f) {
  var a = tests[f], b = diff[f];
  var map = (a || b).branchMap;
  var src = fs.readFileSync(path.join(ROOT, 'vendor/oref0/lib', f), 'utf8').split('\n');
  var r = { modelled: MODELLED.indexOf(f) >= 0, branches: 0, oref0Tests: 0, difftest: 0,
    combined: 0, onlyOref0Tests: 0, onlyDifftest: 0, missed: [] };
  Object.keys(map).forEach(function (k) {
    map[k].locations.forEach(function (loc, i) {
      var ha = hits(a, k, i), hb = hits(b, k, i);
      r.branches++;
      if (ha) r.oref0Tests++;
      if (hb) r.difftest++;
      if (ha || hb) r.combined++;
      if (ha && !hb) r.onlyOref0Tests++;
      if (hb && !ha) r.onlyDifftest++;
      if (!ha && !hb) {
        var line = map[k].line;
        r.missed.push({ line: line, type: map[k].type, outcome: i,
          source: (src[line - 1] || '').trim().slice(0, 120) });
      }
    });
  });
  result.files[f] = r;
});

fs.writeFileSync(path.join(ROOT, 'docs/coverage.json'), JSON.stringify(result, null, 1) + '\n');

function pct(x, n) { return n ? (100 * x / n).toFixed(1) + ' %' : '–'; }
function cell(x, n, reached) { return reached ? x + ' / ' + n + ' (' + pct(x, n) + ')' : 'not reached'; }

var md = [];
md.push('# Branch coverage of oref0');
md.push('');
md.push('Generated by `bash scripts/coverage/run.sh ' + N + ' ' + S + '` (istanbul 0.4.5, declared by oref0)');
md.push('on ' + result.generated.slice(0, 10) + '. Source: `vendor/oref0/lib` (0.7.1). A branch is one outcome');
md.push('of an `if`, `?:`, `switch` case, or one operand of `&&` / `||`. "oref0 tests" is oref0\'s own');
md.push('mocha suite; "difftest" is `scripts/difftest/run.js` with ' + N + ' random cases (seed ' + S + '),');
md.push('which calls `getLastGlucose`, `determine_basal` and `setTempBasal` with ready-made IOB and meal');
md.push('data, so it does not reach `lib/iob` or `lib/meal`. Full data: `docs/coverage.json`.');
md.push('');
md.push('## Files modelled in Lean');
md.push('');
md.push('| file | branches | oref0 tests | difftest | combined |');
md.push('|---|--:|--:|--:|--:|');
var other = [];
files.forEach(function (f) {
  var r = result.files[f];
  var row = '| `' + f + '` | ' + r.branches + ' | ' + cell(r.oref0Tests, r.branches, !!tests[f]) + ' | ' +
    cell(r.difftest, r.branches, !!diff[f]) + ' | ' + r.combined + ' (' + pct(r.combined, r.branches) + ') |';
  if (r.modelled) md.push(row); else other.push(row);
});
md.push('');
md.push('## Branches of the modelled files reached by neither');
md.push('');
files.forEach(function (f) {
  var r = result.files[f];
  if (!r.modelled || !r.missed.length) return;
  md.push('### `' + f + '` (' + r.missed.length + ')');
  md.push('');
  md.push('| line | kind | outcome | source |');
  md.push('|--:|---|--:|---|');
  r.missed.forEach(function (m) {
    md.push('| ' + m.line + ' | ' + m.type + ' | ' + m.outcome + ' | `' + m.source.replace(/\|/g, '\\|') + '` |');
  });
  md.push('');
});
md.push('Outcome 0 is the `then` side of an `if` (or the first operand), 1 the `else` side (or the second).');
md.push('');
md.push('## Other files loaded by the tests (not modelled)');
md.push('');
md.push('| file | branches | oref0 tests | difftest | combined |');
md.push('|---|--:|--:|--:|--:|');
other.forEach(function (row) { md.push(row); });
md.push('');
fs.writeFileSync(path.join(ROOT, 'docs/COVERAGE.md'), md.join('\n'));

files.forEach(function (f) {
  var r = result.files[f];
  if (r.modelled) console.log(f + ': combined ' + r.combined + '/' + r.branches + ' (' + pct(r.combined, r.branches) + ')');
});
console.log('wrote docs/coverage.json, docs/COVERAGE.md');
