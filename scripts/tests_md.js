#!/usr/bin/env node
// Generates docs/TESTS.md from docs/tests-inventory.json (scripts/inventory.js),
// scripts/test-classes.json (classification) and scripts/test-theorems.json
// (theorem name and status per test, filled in at M4/M6).
'use strict';
var fs = require('fs');
var path = require('path');
var ROOT = path.resolve(__dirname, '..');
var inv = JSON.parse(fs.readFileSync(path.join(ROOT, 'docs/tests-inventory.json'), 'utf8'));
var cls = JSON.parse(fs.readFileSync(path.join(__dirname, 'test-classes.json'), 'utf8'));
var thmPath = path.join(__dirname, 'test-theorems.json');
var thm = fs.existsSync(thmPath) ? JSON.parse(fs.readFileSync(thmPath, 'utf8')) : {};

function esc(s) { return String(s).replace(/\|/g, '\\|').replace(/\n/g, ' '); }
function code(xs) { return xs.length ? xs.map(function (x) { return '`' + esc(x) + '`'; }).join('<br>') : '(shared defaults)'; }

var counts = {}, total = 0;
inv.forEach(function (t) {
  var c = (cls[t.id] || {}).class || '?';
  counts[c] = (counts[c] || 0) + 1; total++;
});

var out = [];
out.push('# Test inventory');
out.push('');
out.push('Generated by `scripts/tests_md.js` from `docs/tests-inventory.json` (extracted from');
out.push('`vendor/oref0/tests/*.test.js` by `scripts/inventory.js`), `scripts/test-classes.json`');
out.push('and `scripts/test-theorems.json`. Do not edit by hand.');
out.push('');
out.push('In-scope test files: `determine-basal.test.js` (round_basal and determine-basal),');
out.push('`iob.test.js`, `set-temp-basal.test.js`, `basal.test.js`, `get-last-glucose.test.js`,');
out.push('`cobhistory.test.js`. Out of scope: `profile.test.js` (profile generation, and broken');
out.push('upstream), `bolus.test.js` (pump bolus record parsing),');
out.push('`with-raw-glucose.test.js` (raw CGM), syntax and shell tests.');
out.push('');
out.push('Classes: **A** generalises to a universal property; **B** generalises to a directional');
out.push('property; **C** only meaningful as a concrete check; **D** disabled upstream (commented');
out.push('out in oref0; not asserted, but its inputs are still run through both implementations');
out.push('where they are complete).');
out.push('');
out.push('Inputs show only what the test overrides; the shared defaults of `determine-basal.test.js`');
out.push('are `glucose_status = {delta:0, glucose:115, long_avgdelta:1.1, short_avgdelta:0}`,');
out.push('`currenttemp = {duration:0, rate:0, temp:"absolute"}`, `iob_data = {iob:0, activity:0, bolussnooze:0}`,');
out.push('`autosens = {ratio:1}`, `profile = {max_iob:2.5, dia:3, type:"current", current_basal:0.9,');
out.push('max_daily_basal:1.3, max_basal:3.5, max_bg:120, min_bg:110, sens:40, carb_ratio:10}`,');
out.push('`meal_data = {carbs:50, mealCOB:0, ..., bwFound:false}`. Some tests mutate the shared');
out.push('`profile` and later tests inherit the change (DB-65 to DB-70).');
out.push('');
out.push('**Totals:** ' + total + ' test blocks: ' + Object.keys(counts).sort().map(function (k) { return counts[k] + ' ' + k; }).join(', ') + '.');
out.push('DB-05 is one block that mocha runs as 6 tests, so mocha reports 52 active determine-basal tests.');
out.push('');
out.push('| id | test | inputs (overrides) | expected (assertions) | class | generalisation | theorem | status |');
out.push('|---|---|---|---|---|---|---|---|');
inv.forEach(function (t) {
  var c = cls[t.id] || {};
  var th = thm[t.id] || {};
  out.push('| ' + [
    t.id + (t.commented ? ' (disabled)' : ''),
    esc(t.name) + ' <br><sub>' + t.file + ':' + t.line + '</sub>',
    code(t.inputs),
    code(t.asserts),
    c.class || '?',
    esc(c.general || ''),
    th.theorem ? '`' + th.theorem + '`' : '',
    esc(th.status || '')
  ].join(' | ') + ' |');
});
fs.writeFileSync(path.join(ROOT, 'docs/TESTS.md'), out.join('\n') + '\n');
console.log('docs/TESTS.md: ' + total + ' tests', JSON.stringify(counts));
